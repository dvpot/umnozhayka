"""Rebuild the bundled Russian voice with eSpeak NG 1.51 and FFmpeg."""
import json
import subprocess
import tempfile
import wave
from pathlib import Path

ASSETS = Path(__file__).resolve().parents[1] / "app" / "assets"
NUMBERS = range(1, 11)
PHRASES = [
    *[str(n) for n in sorted({a * b for a in NUMBERS for b in NUMBERS})],
    *[f"{n} умножить на" for n in NUMBERS],
    "Верно!",
    "Попробуй ещё раз.",
    "Звук включён.",
    "Звук выключен.",
    "Привет, я Умножайка.",
]


def generate(folder):
    clip = folder / "clip.wav"
    sprite = folder / "sprite.wav"
    cues = {}
    with wave.open(str(sprite), "wb") as output:
        output.setparams((1, 2, 22050, 0, "NONE", "not compressed"))
        for phrase in PHRASES:
            subprocess.run(
                ["espeak-ng", "-v", "ru", "-s", "145", "-z", "-w", str(clip), phrase],
                check=True,
            )
            with wave.open(str(clip), "rb") as source:
                assert (source.getnchannels(), source.getsampwidth(), source.getframerate()) == (1, 2, 22050)
                start = output.getnframes() / 22050
                duration = source.getnframes() / 22050
                cues[phrase] = [round(start, 5), round(duration, 5)]
                output.writeframes(source.readframes(source.getnframes()))
                output.writeframes(bytes(2205 * 2))
    subprocess.run(
        ["ffmpeg", "-v", "error", "-y", "-i", str(sprite), "-codec:a", "libmp3lame",
         "-b:a", "32k", str(ASSETS / "voice-ru.mp3")],
        check=True,
    )
    (ASSETS / "voice-cues.js").write_text(
        "// Generated by scripts/generate-voice.py. Values are seconds.\n"
        f"export const voiceCues = {json.dumps(cues, ensure_ascii=False, indent=2)};\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    with tempfile.TemporaryDirectory() as folder:
        generate(Path(folder))
